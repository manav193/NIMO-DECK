import { describe, it, expect, vi } from 'vitest';
import { ChangelogGenerator } from '../src/changelog/changelog-generator.js';
import type { CommitRecord } from '@nimo-deck/shared';
import type { AIProviderAdapter } from '@nimo-deck/intelligence';

describe('@nimo-deck/vault: ChangelogGenerator', () => {
  it('should categorize conventional commits and format markdown with strict provenance tags', async () => {
    const generator = new ChangelogGenerator();

    const sampleCommits: CommitRecord[] = [
      {
        id: '1',
        projectId: 'proj-1',
        commitSha: 'a1b2c3d4e5f67890123456789012345678901234',
        branch: 'main',
        authorName: 'Developer',
        authorEmail: 'dev@nimo.io',
        message: 'feat(vault): add CAS blob storage and deduplication',
        filesChangedCount: 3,
        isAutoGenerated: false,
        committedAt: new Date('2026-11-09T10:00:00Z')
      },
      {
        id: '2',
        projectId: 'proj-1',
        commitSha: 'b2c3d4e5f6a17890123456789012345678901234',
        branch: 'main',
        authorName: 'Developer',
        authorEmail: 'dev@nimo.io',
        message: 'fix(restore): prevent path traversal in restored paths',
        filesChangedCount: 1,
        isAutoGenerated: false,
        committedAt: new Date('2026-11-09T11:00:00Z')
      },
      {
        id: '3',
        projectId: 'proj-1',
        commitSha: 'c3d4e5f6a1b27890123456789012345678901234',
        branch: 'main',
        authorName: 'Developer',
        authorEmail: 'dev@nimo.io',
        message: 'feat!: redesign configuration file schema\n\nBREAKING CHANGE: old config format deprecated',
        filesChangedCount: 5,
        isAutoGenerated: false,
        committedAt: new Date('2026-11-09T12:00:00Z')
      }
    ];

    const changelog = await generator.generateChangelog({
      projectId: 'proj-1',
      version: 'v1.1.0',
      title: 'Release v1.1.0 — Vault Subsystem',
      commits: sampleCommits
    });

    expect(changelog.version).toBe('v1.1.0');
    expect(changelog.features.length).toBe(1);
    expect(changelog.fixes.length).toBe(1);
    expect(changelog.breakingChanges.length).toBe(1);

    expect(changelog.markdown).toContain('# Release v1.1.0 — Vault Subsystem (v1.1.0)');
    expect(changelog.markdown).toContain('### ⚠️ Breaking Changes [VERIFIED_GIT_HISTORY]');
    expect(changelog.markdown).toContain('### 🚀 New Features [VERIFIED_GIT_HISTORY]');
    expect(changelog.markdown).toContain('### 🐛 Bug Fixes [VERIFIED_GIT_HISTORY]');
  });

  it('should incorporate AI-synthesized narrative when an AI provider is supplied', async () => {
    const generator = new ChangelogGenerator();

    const mockAiProvider: Partial<AIProviderAdapter> = {
      providerName: 'OpenAI',
      generateText: vi.fn().mockResolvedValue({
        text: 'This milestone introduces core disaster recovery features with zero data loss guarantees.',
        model: 'gpt-4o',
        tokenUsage: { promptTokens: 50, completionTokens: 20, totalTokens: 70 }
      })
    };

    const commits: CommitRecord[] = [
      {
        id: '1',
        projectId: 'proj-1',
        commitSha: '1111222233334444555566667777888899990000',
        branch: 'main',
        authorName: 'Dev',
        authorEmail: 'dev@nimo.io',
        message: 'feat: add recovery engine',
        filesChangedCount: 2,
        isAutoGenerated: false,
        committedAt: new Date()
      }
    ];

    const changelog = await generator.generateChangelog({
      projectId: 'proj-1',
      version: 'v1.2.0',
      title: 'Release v1.2.0',
      commits,
      aiProvider: mockAiProvider as AIProviderAdapter
    });

    expect(changelog.aiNarrative).toBe('This milestone introduces core disaster recovery features with zero data loss guarantees.');
    expect(changelog.markdown).toContain('### 🤖 Executive Overview [AI_GENERATED_INTERPRETATION]');
  });
});
