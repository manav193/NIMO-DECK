import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import { createDatabaseConnection, runMigrations } from '@nimo-deck/core';
import { DeckVaultEngine } from '../src/engine/deck-vault-engine.js';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import type Database from 'better-sqlite3';

describe('@nimo-deck/vault: DeckVaultEngine End-to-End', () => {
  let sqlite: Database.Database;
  let tempVaultDir: string;
  let tempProjectDir: string;
  let engine: DeckVaultEngine;
  const projectId = '55555555-5555-5555-5555-555555555555';

  beforeEach(() => {
    const conn = createDatabaseConnection({ inMemory: true });
    sqlite = conn.sqlite;
    runMigrations(sqlite);

    tempVaultDir = fs.mkdtempSync(path.join(os.tmpdir(), 'nimo-deck-vault-dir-'));
    tempProjectDir = fs.mkdtempSync(path.join(os.tmpdir(), 'nimo-deck-proj-dir-'));

    // Register project in DB
    const now = Date.now();
    sqlite.prepare('INSERT INTO projects (id, name, local_path, created_at, updated_at) VALUES (?, ?, ?, ?, ?)').run(
      projectId,
      'Nexus Core',
      tempProjectDir,
      now,
      now
    );

    // Create project files
    fs.mkdirSync(path.join(tempProjectDir, 'src'), { recursive: true });
    fs.writeFileSync(path.join(tempProjectDir, 'src', 'index.ts'), 'export const nexus = "online";\n');
    fs.writeFileSync(path.join(tempProjectDir, 'README.md'), '# Nexus Core Project\n');

    engine = new DeckVaultEngine({
      db: conn.db,
      vaultDir: tempVaultDir
    });
  });

  afterEach(() => {
    sqlite.close();
    fs.rmSync(tempVaultDir, { recursive: true, force: true });
    fs.rmSync(tempProjectDir, { recursive: true, force: true });
  });

  it('should execute end-to-end workflow: snapshot -> audit -> preview -> restore -> changelog -> retention', async () => {
    // 1. Create initial snapshot
    const snapResult = await engine.createSnapshot({
      projectId,
      projectPath: tempProjectDir,
      description: 'Initial project checkpoint'
    });

    expect(snapResult.snapshot.id).toBeDefined();
    expect(snapResult.snapshot.fileCount).toBe(2);
    expect(snapResult.manifest.rootHash).toHaveLength(64);

    // 2. Verify audit chain includes snapshot creation event
    const auditReport = engine.verifyAuditChain();
    expect(auditReport.isValid).toBe(true);
    expect(auditReport.totalVerified).toBe(1);

    const auditLogs = engine.queryAuditLogs({ projectId });
    expect(auditLogs.length).toBe(1);
    expect(auditLogs[0].action).toBe('VAULT_SNAPSHOT_CREATED');

    // 3. Mutate files in project
    fs.writeFileSync(path.join(tempProjectDir, 'src', 'index.ts'), 'export const nexus = "corrupted";\n');
    fs.writeFileSync(path.join(tempProjectDir, 'temp-file.tmp'), 'should be removed\n');

    // 4. Generate restore preview
    const preview = engine.generateRestorePreview(snapResult.manifest, tempProjectDir);
    expect(preview.filesToOverwrite).toEqual(['src/index.ts']);
    expect(preview.filesToDelete).toEqual(['temp-file.tmp']);
    expect(preview.isWorkingTreeDirty).toBe(true);

    // 5. Restore snapshot safely
    const restoreResult = await engine.restoreSnapshot({
      snapshot: snapResult.snapshot,
      manifest: snapResult.manifest,
      projectPath: tempProjectDir,
      confirmRestore: true,
      allowOverwriteUncommitted: true,
      allowDeletion: true
    });

    expect(restoreResult.success).toBe(true);
    expect(restoreResult.restoredFileCount).toBe(2);
    expect(restoreResult.safetySnapshotId).toBeDefined();

    // Verify disk content was restored
    const restoredIndex = fs.readFileSync(path.join(tempProjectDir, 'src', 'index.ts'), 'utf-8');
    expect(restoredIndex).toBe('export const nexus = "online";\n');
    expect(fs.existsSync(path.join(tempProjectDir, 'temp-file.tmp'))).toBe(false);

    // 6. Generate changelog
    const changelog = await engine.generateChangelog({
      projectId,
      version: 'v1.0.0',
      title: 'Initial Nexus Launch',
      commits: [
        {
          id: 'c1',
          projectId,
          commitSha: 'a1b2c3d4e5f67890123456789012345678901234',
          branch: 'main',
          authorName: 'Architect',
          authorEmail: 'lead@nimo.io',
          message: 'feat(core): initial kernel initialization',
          filesChangedCount: 2,
          isAutoGenerated: false,
          committedAt: new Date()
        }
      ]
    });

    expect(changelog.version).toBe('v1.0.0');
    expect(changelog.features.length).toBe(1);
    expect(changelog.markdown).toContain('Initial Nexus Launch');

    // 7. Verify unified developer timeline
    const timeline = engine.getTimeline({ projectId });
    expect(timeline.length).toBeGreaterThanOrEqual(2);

    // 8. Verify audit chain is still 100% cryptographically consistent
    const finalAuditReport = engine.verifyAuditChain();
    expect(finalAuditReport.isValid).toBe(true);
    expect(finalAuditReport.totalVerified).toBeGreaterThanOrEqual(3);

    // 9. Apply retention policies
    const retentionResult = engine.applyRetention(projectId, { maxSnapshotsPerProject: 10 });
    expect(retentionResult.snapshotsRetained).toBeGreaterThanOrEqual(1);
  });
});
