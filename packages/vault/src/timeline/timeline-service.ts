import type { DeckDatabase } from '@nimo-deck/core';
import {
  commitHistory,
  syncEvents,
  driveBackups,
  aiAnalyses,
  vaultSnapshots,
  auditLogs
} from '@nimo-deck/core';
import { eq, desc } from 'drizzle-orm';
import type { TimelineEvent, TimelineEventType } from '@nimo-deck/shared';

export interface TimelineFilter {
  projectId: string;
  types?: TimelineEventType[];
  search?: string;
  startDate?: Date;
  endDate?: Date;
  limit?: number;
}

export class ProjectTimelineService {
  constructor(private db: DeckDatabase) {}

  /**
   * Aggregates events across Git commits, sync cycles, Drive backups, AI analyses,
   * snapshots, and user actions into a unified chronological developer timeline.
   */
  getProjectTimeline(filter: TimelineFilter): TimelineEvent[] {
    const events: TimelineEvent[] = [];

    // 1. Git Commits
    const commits = this.db
      .select()
      .from(commitHistory)
      .where(eq(commitHistory.projectId, filter.projectId))
      .orderBy(desc(commitHistory.committedAt))
      .limit(filter.limit || 100)
      .all();

    for (const c of commits) {
      events.push({
        id: `commit-${c.id}`,
        projectId: c.projectId,
        timestamp: c.committedAt,
        type: 'GIT_COMMIT',
        title: `Git Commit: ${c.message.split('\n')[0]}`,
        description: `${c.filesChangedCount} files changed by ${c.authorName} on branch ${c.branch}`,
        actor: c.authorName,
        commitSha: c.commitSha,
        metadata: {
          authorEmail: c.authorEmail,
          isAutoGenerated: Boolean(c.isAutoGenerated)
        }
      });
    }

    // 2. Sync Events
    const syncs = this.db
      .select()
      .from(syncEvents)
      .where(eq(syncEvents.projectId, filter.projectId))
      .orderBy(desc(syncEvents.createdAt))
      .limit(filter.limit || 100)
      .all();

    for (const s of syncs) {
      events.push({
        id: `sync-${s.id}`,
        projectId: s.projectId,
        timestamp: s.createdAt,
        type: 'SYNC_CYCLE',
        title: `Sync Event: ${s.eventType} (${s.status})`,
        description: `Automated sync operation ${s.status.toLowerCase()}`,
        actor: 'SYSTEM',
        metadata: JSON.parse(s.detailsJson || '{}')
      });
    }

    // 3. Drive Backups
    const backups = this.db
      .select()
      .from(driveBackups)
      .where(eq(driveBackups.projectId, filter.projectId))
      .orderBy(desc(driveBackups.createdAt))
      .limit(filter.limit || 100)
      .all();

    for (const b of backups) {
      events.push({
        id: `drive-${b.id}`,
        projectId: b.projectId,
        timestamp: b.createdAt,
        type: 'DRIVE_BACKUP',
        title: `Google Drive ${b.backupType} Backup`,
        description: `Uploaded ${b.backupType.toLowerCase()} (${b.sizeBytes} bytes) - status: ${b.status}`,
        actor: 'SYSTEM',
        metadata: {
          driveFileId: b.driveFileId,
          snapshotSha256: b.snapshotSha256
        }
      });
    }

    // 4. AI Analysis Events
    const analyses = this.db
      .select()
      .from(aiAnalyses)
      .where(eq(aiAnalyses.projectId, filter.projectId))
      .orderBy(desc(aiAnalyses.createdAt))
      .limit(filter.limit || 100)
      .all();

    for (const a of analyses) {
      events.push({
        id: `ai-${a.id}`,
        projectId: a.projectId,
        timestamp: a.createdAt,
        type: 'AI_ANALYSIS',
        title: `AI Intelligence Analysis (${a.modelUsed})`,
        description: `Completed cognitive audit using model ${a.modelUsed}`,
        actor: 'AI_AGENT',
        commitSha: a.commitSha || undefined,
        metadata: {
          promptVersion: a.promptVersion
        }
      });
    }

    // 5. Vault Snapshots
    const snapshots = this.db
      .select()
      .from(vaultSnapshots)
      .where(eq(vaultSnapshots.projectId, filter.projectId))
      .orderBy(desc(vaultSnapshots.createdAt))
      .limit(filter.limit || 100)
      .all();

    for (const snap of snapshots) {
      events.push({
        id: `snap-${snap.id}`,
        projectId: snap.projectId,
        timestamp: snap.createdAt,
        type: 'VAULT_SNAPSHOT',
        title: `Vault Snapshot: ${snap.description}`,
        description: `Captured ${snap.snapshotType} snapshot (${snap.fileCount} files, ${snap.sizeBytes} bytes)`,
        actor: 'SYSTEM',
        commitSha: snap.commitSha || undefined,
        metadata: {
          snapshotType: snap.snapshotType,
          rootHash: snap.rootHash,
          isPinned: snap.isPinned
        }
      });
    }

    // 6. User / System Audit Actions
    const audits = this.db
      .select()
      .from(auditLogs)
      .where(eq(auditLogs.projectId, filter.projectId))
      .orderBy(desc(auditLogs.createdAt))
      .limit(filter.limit || 100)
      .all();

    for (const aud of audits) {
      events.push({
        id: `audit-${aud.id}`,
        projectId: aud.projectId || filter.projectId,
        timestamp: aud.createdAt,
        type: aud.action.includes('RESTORE') ? 'VAULT_RESTORE' : 'USER_ACTION',
        title: `Audit Action: ${aud.action}`,
        description: `Execution logged by ${aud.actor}`,
        actor: aud.actor,
        metadata: {
          payloadHash: aud.payloadHash,
          entryHash: aud.entryHash
        }
      });
    }

    // Sort chronologically descending
    let sorted = events.sort((a, b) => b.timestamp.getTime() - a.timestamp.getTime());

    // Apply filters
    if (filter.types && filter.types.length > 0) {
      const typeSet = new Set(filter.types);
      sorted = sorted.filter((e) => typeSet.has(e.type));
    }

    if (filter.search) {
      const q = filter.search.toLowerCase();
      sorted = sorted.filter(
        (e) => e.title.toLowerCase().includes(q) || e.description.toLowerCase().includes(q)
      );
    }

    if (filter.startDate) {
      sorted = sorted.filter((e) => e.timestamp >= filter.startDate!);
    }

    if (filter.endDate) {
      sorted = sorted.filter((e) => e.timestamp <= filter.endDate!);
    }

    return sorted.slice(0, filter.limit || 100);
  }
}
