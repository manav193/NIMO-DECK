import { z } from 'zod';

export const AutoPushModeSchema = z.enum(['OFF', 'ON_COMMIT', 'SCHEDULED']);
export type AutoPushMode = z.infer<typeof AutoPushModeSchema>;

export const SyncConfigSchema = z.object({
  projectId: z.string().uuid(),
  autoCommitEnabled: z.boolean().default(true),
  debounceWindowMs: z.number().int().min(1000).max(60000).default(5000),
  maxWaitMs: z.number().int().min(5000).max(300000).default(30000),
  autoPushMode: AutoPushModeSchema.default('ON_COMMIT'),
  pushIntervalSec: z.number().int().min(30).max(86400).default(300),
  aiCommitMessages: z.boolean().default(false),
  dryRunMode: z.boolean().default(false),
  updatedAt: z.date()
});
export type SyncConfig = z.infer<typeof SyncConfigSchema>;

export const UpdateSyncConfigInputSchema = SyncConfigSchema.omit({
  projectId: true,
  updatedAt: true
}).partial();
export type UpdateSyncConfigInput = z.infer<typeof UpdateSyncConfigInputSchema>;

export const SyncEventTypeSchema = z.enum([
  'FILE_CHANGED',
  'BATCH_DEBOUNCED',
  'SECRET_DETECTED',
  'COMMIT_CREATED',
  'PULL_SUCCEEDED',
  'PULL_FAILED',
  'PUSH_SUCCEEDED',
  'PUSH_FAILED',
  'CONFLICT_DETECTED',
  'HEALTH_WARNING'
]);
export type SyncEventType = z.infer<typeof SyncEventTypeSchema>;

export const SyncEventStatusSchema = z.enum(['SUCCESS', 'PENDING', 'FAILED']);
export type SyncEventStatus = z.infer<typeof SyncEventStatusSchema>;

export const SyncEventSchema = z.object({
  id: z.string().uuid(),
  projectId: z.string().uuid(),
  eventType: SyncEventTypeSchema,
  status: SyncEventStatusSchema,
  details: z.record(z.string(), z.unknown()),
  createdAt: z.date()
});
export type SyncEvent = z.infer<typeof SyncEventSchema>;

export const CommitRecordSchema = z.object({
  id: z.string().uuid(),
  projectId: z.string().uuid(),
  commitSha: z.string().length(40),
  branch: z.string().min(1),
  authorName: z.string().min(1),
  authorEmail: z.string().email(),
  message: z.string().min(1),
  filesChangedCount: z.number().int().nonnegative(),
  isAutoGenerated: z.boolean(),
  committedAt: z.date()
});
export type CommitRecord = z.infer<typeof CommitRecordSchema>;

export const RemoteSyncStatusSchema = z.enum(['IN_SYNC', 'AHEAD', 'BEHIND', 'DIVERGED']);
export type RemoteSyncStatus = z.infer<typeof RemoteSyncStatusSchema>;

export const RemoteSyncStateSchema = z.object({
  id: z.string().uuid(),
  projectId: z.string().uuid(),
  branchName: z.string().min(1),
  localHeadSha: z.string().length(40),
  remoteHeadSha: z.string().length(40),
  syncStatus: RemoteSyncStatusSchema,
  lastSyncedAt: z.date()
});
export type RemoteSyncState = z.infer<typeof RemoteSyncStateSchema>;
