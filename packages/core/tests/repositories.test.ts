import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import {
  createDatabaseConnection,
  ProjectRepository,
  SyncConfigRepository,
  SyncEventRepository,
  CommitHistoryRepository,
  RemoteSyncStateRepository,
  AIAnalysisRepository
} from '../src/index.js';
import type Database from 'better-sqlite3';

describe('@nimo-deck/core: Repositories', () => {
  let sqlite: Database.Database;
  let projectRepo: ProjectRepository;
  let syncConfigRepo: SyncConfigRepository;
  let syncEventRepo: SyncEventRepository;
  let commitRepo: CommitHistoryRepository;
  let remoteSyncRepo: RemoteSyncStateRepository;
  let aiRepo: AIAnalysisRepository;

  beforeEach(() => {
    const conn = createDatabaseConnection({ inMemory: true });
    sqlite = conn.sqlite;
    projectRepo = new ProjectRepository(conn.db);
    syncConfigRepo = new SyncConfigRepository(conn.db);
    syncEventRepo = new SyncEventRepository(conn.db);
    commitRepo = new CommitHistoryRepository(conn.db);
    remoteSyncRepo = new RemoteSyncStateRepository(conn.db);
    aiRepo = new AIAnalysisRepository(conn.db);
  });

  afterEach(() => {
    sqlite.close();
  });

  it('should create and retrieve a project with auto-initialized sync config', () => {
    const project = projectRepo.create({
      name: 'NIMO-DECK',
      localPath: 'C:\\Projects\\NIMO-DECK',
      gitRemoteUrl: 'https://github.com/manav193/NIMO-DECK'
    });

    expect(project.id).toBeDefined();
    expect(project.name).toBe('NIMO-DECK');
    expect(project.status).toBe('ACTIVE');

    const retrieved = projectRepo.getById(project.id);
    expect(retrieved).not.toBeNull();
    expect(retrieved?.localPath).toBe('C:\\Projects\\NIMO-DECK');

    const config = syncConfigRepo.getByProjectId(project.id);
    expect(config).not.toBeNull();
    expect(config?.autoCommitEnabled).toBe(true);
    expect(config?.debounceWindowMs).toBe(5000);
  });

  it('should update sync configuration for a project', () => {
    const project = projectRepo.create({
      name: 'AlphaProject',
      localPath: 'C:\\Projects\\Alpha'
    });

    const updated = syncConfigRepo.update(project.id, {
      debounceWindowMs: 8000,
      autoPushMode: 'SCHEDULED',
      pushIntervalSec: 600,
      aiCommitMessages: true
    });

    expect(updated).not.toBeNull();
    expect(updated?.debounceWindowMs).toBe(8000);
    expect(updated?.autoPushMode).toBe('SCHEDULED');
    expect(updated?.pushIntervalSec).toBe(600);
    expect(updated?.aiCommitMessages).toBe(true);
  });

  it('should log sync events and retrieve recent event history', () => {
    const project = projectRepo.create({
      name: 'BetaProject',
      localPath: 'C:\\Projects\\Beta'
    });

    const now = Date.now();
    syncEventRepo.logEvent({
      projectId: project.id,
      eventType: 'FILE_CHANGED',
      status: 'SUCCESS',
      details: { filesCount: 3, paths: ['src/a.ts', 'src/b.ts'] },
      createdAt: new Date(now - 1000)
    });

    syncEventRepo.logEvent({
      projectId: project.id,
      eventType: 'COMMIT_CREATED',
      status: 'SUCCESS',
      details: { commitSha: 'abcdef1234567890abcdef1234567890abcdef12' },
      createdAt: new Date(now)
    });

    const events = syncEventRepo.listByProject(project.id);
    expect(events).toHaveLength(2);
    expect(events[0].eventType).toBe('COMMIT_CREATED');
    expect(events[1].eventType).toBe('FILE_CHANGED');
  });

  it('should record commits and query latest commit', () => {
    const project = projectRepo.create({
      name: 'GammaProject',
      localPath: 'C:\\Projects\\Gamma'
    });

    const sha1 = '1111111111111111111111111111111111111111';
    const sha2 = '2222222222222222222222222222222222222222';

    commitRepo.recordCommit({
      projectId: project.id,
      commitSha: sha1,
      branch: 'main',
      authorName: 'Manav',
      authorEmail: 'manav@example.com',
      message: 'feat: initial commit',
      filesChangedCount: 5,
      isAutoGenerated: false,
      committedAt: new Date(Date.now() - 10000)
    });

    commitRepo.recordCommit({
      projectId: project.id,
      commitSha: sha2,
      branch: 'main',
      authorName: 'NIMO-DECK Sync Engine',
      authorEmail: 'deck-sync@local',
      message: 'chore: auto commit file changes',
      filesChangedCount: 2,
      isAutoGenerated: true,
      committedAt: new Date()
    });

    const latest = commitRepo.getLatestCommit(project.id);
    expect(latest).not.toBeNull();
    expect(latest?.commitSha).toBe(sha2);
    expect(latest?.isAutoGenerated).toBe(true);

    const allCommits = commitRepo.listByProject(project.id);
    expect(allCommits).toHaveLength(2);
  });

  it('should upsert and track remote sync states', () => {
    const project = projectRepo.create({
      name: 'DeltaProject',
      localPath: 'C:\\Projects\\Delta'
    });

    const state1 = remoteSyncRepo.upsertState({
      projectId: project.id,
      branchName: 'main',
      localHeadSha: 'aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa',
      remoteHeadSha: 'bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb',
      syncStatus: 'BEHIND'
    });

    expect(state1.syncStatus).toBe('BEHIND');

    // Update state to in-sync
    const state2 = remoteSyncRepo.upsertState({
      projectId: project.id,
      branchName: 'main',
      localHeadSha: 'bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb',
      remoteHeadSha: 'bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb',
      syncStatus: 'IN_SYNC'
    });

    expect(state2.id).toBe(state1.id);
    expect(state2.syncStatus).toBe('IN_SYNC');
  });

  it('should store AI analyses and recommendations with fact-vs-hypothesis typing', () => {
    const project = projectRepo.create({
      name: 'EpsilonProject',
      localPath: 'C:\\Projects\\Epsilon'
    });

    const analysis = aiRepo.saveAnalysis({
      projectId: project.id,
      modelUsed: 'openrouter/anthropic/claude-3.5-sonnet',
      summaryMarkdown: '# Architecture Summary\nModular monorepo structure.',
      techDebtReport: 'No circular dependencies detected.',
      securityReport: 'Zero exposed secrets.'
    });

    const factRec = aiRepo.saveRecommendation({
      analysisId: analysis.id,
      projectId: project.id,
      title: 'Upgrade React',
      category: 'VERIFIED_FACT',
      severity: 'HIGH',
      complexity: 'M',
      reasoning: 'React version is outdated in package.json',
      expectedBenefits: 'Concurrent features',
      dependencies: ['react@19'],
      implementationSteps: ['npm update']
    });

    const hypothesisRec = aiRepo.saveRecommendation({
      analysisId: analysis.id,
      projectId: project.id,
      title: 'Adopt SQLite WAL mode',
      category: 'AI_HYPOTHESIS',
      severity: 'MEDIUM',
      complexity: 'S',
      reasoning: 'Concurrent read throughput might improve by 30%',
      expectedBenefits: 'Reduced lock contention',
      dependencies: [],
      implementationSteps: ['Set pragma journal_mode = WAL']
    });

    const projectRecs = aiRepo.listRecommendationsByProject(project.id);
    expect(projectRecs).toHaveLength(2);
    expect(projectRecs.find((r) => r.category === 'VERIFIED_FACT')?.id).toBe(factRec.id);
    expect(projectRecs.find((r) => r.category === 'AI_HYPOTHESIS')?.id).toBe(hypothesisRec.id);

    // Update recommendation status
    const accepted = aiRepo.updateRecommendationStatus(factRec.id, 'ACCEPTED');
    expect(accepted).toBe(true);

    const reloaded = aiRepo.getLatestAnalysis(project.id);
    expect(reloaded?.recommendations.find((r) => r.id === factRec.id)?.status).toBe('ACCEPTED');
  });

  it('should cascade delete project records when project is deleted', () => {
    const project = projectRepo.create({
      name: 'ZetaProject',
      localPath: 'C:\\Projects\\Zeta'
    });

    syncEventRepo.logEvent({
      projectId: project.id,
      eventType: 'FILE_CHANGED',
      status: 'SUCCESS',
      details: {}
    });

    expect(projectRepo.delete(project.id)).toBe(true);
    expect(projectRepo.getById(project.id)).toBeNull();
    expect(syncConfigRepo.getByProjectId(project.id)).toBeNull();
    expect(syncEventRepo.listByProject(project.id)).toHaveLength(0);
  });
});
