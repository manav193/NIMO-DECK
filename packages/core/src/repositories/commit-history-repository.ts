import { eq, desc } from 'drizzle-orm';
import type { DeckDatabase } from '../database/connection.js';
import { commitHistory } from '../database/schema.js';
import type { CommitRecord } from '@nimo-deck/shared';
import crypto from 'node:crypto';

export class CommitHistoryRepository {
  constructor(private db: DeckDatabase) {}

  recordCommit(params: {
    projectId: string;
    commitSha: string;
    branch: string;
    authorName: string;
    authorEmail: string;
    message: string;
    filesChangedCount: number;
    isAutoGenerated: boolean;
    committedAt?: Date;
  }): CommitRecord {
    const id = crypto.randomUUID();
    const committedAt = params.committedAt || new Date();

    const record: typeof commitHistory.$inferInsert = {
      id,
      projectId: params.projectId,
      commitSha: params.commitSha,
      branch: params.branch,
      authorName: params.authorName,
      authorEmail: params.authorEmail,
      message: params.message,
      filesChangedCount: params.filesChangedCount,
      isAutoGenerated: params.isAutoGenerated,
      committedAt
    };

    this.db.insert(commitHistory).values(record).run();

    return {
      id,
      projectId: params.projectId,
      commitSha: params.commitSha,
      branch: params.branch,
      authorName: params.authorName,
      authorEmail: params.authorEmail,
      message: params.message,
      filesChangedCount: params.filesChangedCount,
      isAutoGenerated: params.isAutoGenerated,
      committedAt
    };
  }

  listByProject(projectId: string, limit = 50): CommitRecord[] {
    const rows = this.db
      .select()
      .from(commitHistory)
      .where(eq(commitHistory.projectId, projectId))
      .orderBy(desc(commitHistory.committedAt))
      .limit(limit)
      .all();

    return rows.map((row) => ({
      id: row.id,
      projectId: row.projectId,
      commitSha: row.commitSha,
      branch: row.branch,
      authorName: row.authorName,
      authorEmail: row.authorEmail,
      message: row.message,
      filesChangedCount: row.filesChangedCount,
      isAutoGenerated: row.isAutoGenerated,
      committedAt: row.committedAt
    }));
  }

  getLatestCommit(projectId: string): CommitRecord | null {
    const row = this.db
      .select()
      .from(commitHistory)
      .where(eq(commitHistory.projectId, projectId))
      .orderBy(desc(commitHistory.committedAt))
      .limit(1)
      .get();

    if (!row) return null;

    return {
      id: row.id,
      projectId: row.projectId,
      commitSha: row.commitSha,
      branch: row.branch,
      authorName: row.authorName,
      authorEmail: row.authorEmail,
      message: row.message,
      filesChangedCount: row.filesChangedCount,
      isAutoGenerated: row.isAutoGenerated,
      committedAt: row.committedAt
    };
  }
}
